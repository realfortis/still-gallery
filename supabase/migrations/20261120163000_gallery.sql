begin;

create table public.gallery_staff (
  user_id uuid primary key references auth.users (id) on delete cascade
);

alter table public.gallery_staff enable row level security;
revoke all on public.gallery_staff from public, anon, authenticated;

create function public.is_gallery_staff()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (select 1 from public.gallery_staff where user_id = (select auth.uid()));
$$;
revoke all on function public.is_gallery_staff() from public, anon;
grant execute on function public.is_gallery_staff() to authenticated;

create table public.gallery_artworks (
  id integer generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 120),
  artist text not null check (char_length(btrim(artist)) between 1 and 120),
  medium text not null check (char_length(btrim(medium)) between 1 and 80),
  year text not null default '' check (char_length(year) <= 20),
  dimensions text not null default '' check (char_length(dimensions) <= 80),
  description text not null default '' check (char_length(description) <= 2000),
  alt_text text not null check (char_length(btrim(alt_text)) between 1 and 240),
  status text not null default 'draft' check (status in ('draft', 'published')),
  featured boolean not null default false check (not featured or status = 'published'),
  image_path text unique check (image_path ~ '^[a-f0-9-]{36}\.(jpg|png|webp)$'),
  sample_file text check (sample_file in ('salt-memory.jpg', 'between-headlands.jpg', 'vessel-for-rain.jpg')),
  version integer not null default 1,
  check ((image_path is null) <> (sample_file is null))
);

create unique index gallery_one_featured on public.gallery_artworks (featured) where featured;

create function public.gallery_prepare_artwork()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'UPDATE' then
    new.version := old.version + 1;
  end if;
  if new.status = 'draft' then
    new.featured := false;
  end if;
  if new.featured then
    update public.gallery_artworks set featured = false
      where featured and id <> new.id;
  end if;
  return new;
end;
$$;
revoke all on function public.gallery_prepare_artwork() from public;

create trigger gallery_prepare_artwork
before insert or update on public.gallery_artworks
for each row execute function public.gallery_prepare_artwork();

alter table public.gallery_artworks enable row level security;
revoke all on public.gallery_artworks from public, anon, authenticated;
grant select on public.gallery_artworks to anon, authenticated;
grant insert, update, delete on public.gallery_artworks to authenticated;
grant usage on sequence public.gallery_artworks_id_seq to authenticated;
create policy "Visitors can read published work"
  on public.gallery_artworks for select to anon, authenticated using (status = 'published');
create policy "Staff can manage artwork"
  on public.gallery_artworks for all to authenticated
  using ((select public.is_gallery_staff()))
  with check ((select public.is_gallery_staff()));

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('gallery-artwork', 'gallery-artwork', false, 6291456, array['image/jpeg', 'image/png', 'image/webp']);

create policy "Published artwork images can be read"
  on storage.objects for select to anon, authenticated
  using (bucket_id = 'gallery-artwork' and exists (
    select 1 from public.gallery_artworks
    where image_path = storage.objects.name and status = 'published'
  ));
create policy "Staff can read artwork images"
  on storage.objects for select to authenticated
  using (bucket_id = 'gallery-artwork' and (select public.is_gallery_staff()));
create policy "Staff can upload new artwork images"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'gallery-artwork' and (select public.is_gallery_staff())
    and name ~ '^[a-f0-9-]{36}\.(jpg|png|webp)$');
create policy "Staff can delete unreferenced artwork images"
  on storage.objects for delete to authenticated
  using (bucket_id = 'gallery-artwork' and (select public.is_gallery_staff()) and not exists (
    select 1 from public.gallery_artworks where image_path = storage.objects.name
  ));

